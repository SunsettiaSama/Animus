def main() -> None:
    cases = build_cases()
    problems = validate_dataset(cases)
    if problems:
        raise SystemExit("数据集校验失败：\n" + "\n".join(problems))
    out = Path(__file__).resolve().parent / "data" / "cases.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w", encoding="utf-8", newline="\n") as fh:
        for case in cases:
            fh.write(json.dumps(case.to_dict(), ensure_ascii=False))
            fh.write("\n")
    print(f"written {len(cases)} cases -> {out}")


if __name__ == "__main__":
    main()
