def _m(text: str, focus: str = "", emotion: str = "", valence: str = "neutral",
       days_ago: float = 1.0, tags: list[str] | None = None) -> MemorySeed:
    return MemorySeed(text=text, focus=focus, emotion=emotion, valence=valence,
                      days_ago=days_ago, tags=tags or [])


def _c(case_id: str, category: str, memories: list[MemorySeed], current_user: str,
       history: list[tuple[str, str]] | None = None, must: list[str] | None = None,
       note: str = "") -> HumanenessCase:
    return HumanenessCase(
        case_id=case_id,
        category=category,
        memories=memories,
        current_user=current_user,
        history=[Turn(role=r, text=t) for r, t in (history or [])],
        must_remember=must or [],
        note=note,
    )


