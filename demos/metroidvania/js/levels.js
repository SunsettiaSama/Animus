// 世界状态：当前房间网格 + 碰撞查询
const World = {
  rows: [], w: 0, h: 0, def: null, id: '',
  voidBottom: false, gateClosed: false, bossDefeated: false,

  load(def, id, flags) {
    this.def = def; this.id = id;
    this.w = Math.max(...def.map.map((r) => r.length));
    this.rows = def.map.map((r) => r.padEnd(this.w, '.'));
    this.h = this.rows.length;
    this.voidBottom = !!def.voidBottom;
    this.gateClosed = false;
    this.bossDefeated = def.boss === '1' ? !!flags.boss1 : def.boss === '2' ? !!flags.boss2 : false;
  },

  tileAt(tx, ty) {
    if (tx < 0 || tx >= this.w) return '#';
    if (ty < 0) return '#';
    if (ty >= this.h) return this.voidBottom ? '.' : '#';
    return this.rows[ty][tx];
  },

  isSolid(tx, ty) {
    const t = this.tileAt(tx, ty);
    if (t === '#') return true;
    if (t === 'G') return this.gateClosed;
    if (t === 'H') return !this.bossDefeated;
    return false;
  },

  // 某个矩形范围是否碰到的指定字符（用于地刺检测）
  overlapsTile(ch, x, y, w, h, inset) {
    const i = inset || 0;
    const x0 = Math.floor((x + i) / T), x1 = Math.floor((x + w - i - 0.01) / T);
    const y0 = Math.floor((y + i) / T), y1 = Math.floor((y + h - i - 0.01) / T);
    for (let ty = y0; ty <= y1; ty++)
      for (let tx = x0; tx <= x1; tx++)
        if (this.tileAt(tx, ty) === ch) return true;
    return false;
  }
};
